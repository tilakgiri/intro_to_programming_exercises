# while loop for 1-50 part
# using base as a counter for the while loop
base = 1
while base <= 50:
    print(f"{base}\n")
    base += 1


#for loop for 1-50 part
# running the for loop in a range of 50
for a in range(50):
    a += 1
    print(f"{a}\n")



# sum of 1-50 part
# using total as a variable that stores sum value till the end
total = 0
for base in range(30):
    base += 1
    total = total + base
print(f"{total}\n")

