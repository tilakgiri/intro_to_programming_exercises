# using base as a counter for the while loop
base = 1
# running the while loop until the condition meets
while base <= 50:
    print(f"{base}\n")
    base += 1

# running the for loop in a range of 50
for a in range(50):
    # increasing the counter value by 1 because the index starts from 0
    # but i need it to start from 1-50
    a += 1
    print(f"{a}\n")


